def test_regular_hourly_requires_utc_whole_hour_naive_is_refused():
    naive = pd.DataFrame(
        {"valid_at": pd.date_range("2024-01-01", periods=3, freq="h"), "v": [1, 2, 3]}
    )
    with pytest.raises(ValueError, match="explicit UTC timezone"):
        regular_hourly(naive, "weather")


def test_regular_hourly_refuses_duplicate_timestamps():
    stamps = pd.to_datetime(["2024-01-01 00:00", "2024-01-01 00:00"], utc=True)
    with pytest.raises(ValueError, match="duplicate timestamps"):
        regular_hourly(pd.DataFrame({"valid_at": stamps, "v": [1.0, 2.0]}), "cams")


def test_regular_hourly_refuses_a_timestamp_that_is_not_on_the_hour():
    stamps = pd.to_datetime(["2024-01-01 00:00", "2024-01-01 00:30"], utc=True)
    with pytest.raises(ValueError, match="whole-hour"):
        regular_hourly(pd.DataFrame({"valid_at": stamps, "v": [1.0, 2.0]}), "cams")


def test_regular_hourly_restores_a_missing_hour_as_nan_so_shifts_stay_calendar_hours():
    """Without this a `shift(2)` would silently span three real hours at a gap."""
    stamps = pd.to_datetime(
        ["2024-01-01 00:00", "2024-01-01 01:00", "2024-01-01 03:00", "2024-01-01 04:00"], utc=True
    )
    gap = pd.Timestamp("2024-01-01 02:00", tz="UTC")
    regular = regular_hourly(
        pd.DataFrame({"valid_at": stamps, "pm25_ug_m3": [10.0, 20.0, 40.0, 50.0]}), "cams"
    )

    assert list(regular["valid_at"]) == list(pd.date_range(stamps.min(), stamps.max(), freq="h"))
    assert regular.loc[regular["valid_at"] == gap, "pm25_ug_m3"].isna().all()
    shifted = regular.set_index("valid_at")["pm25_ug_m3"].shift(2)
    assert shifted.loc[pd.Timestamp("2024-01-01 03:00", tz="UTC")] == pytest.approx(20.0)


