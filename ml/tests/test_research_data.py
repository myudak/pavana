def test_text_in_a_numeric_column_is_refused_rather_than_read_as_missing():
    """Coercing with `errors="coerce"` alone would turn "not-a-number" into a silent NaN."""
    frame = pd.DataFrame({"pm25_ug_m3": ["1.0", "not-a-number"]})
    with pytest.raises(ValueError, match="non-finite or non-numeric"):
        value_check(frame, "cams")


