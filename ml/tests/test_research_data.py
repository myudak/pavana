def test_infinite_values_are_refused_even_in_a_one_sided_range(tmp_path, bad):
    """`inf` is not caught by a `< 0` test, so the finiteness check has to be explicit."""
    cams = cams_frame()
    cams.loc[0, "pm25_ug_m3"] = bad
