def test_prepare_cached_data_aligns_sources_and_keeps_each_grid_coordinate(tmp_path):
    hourly, hotspots, report = prepare_cached_data(write_cache(tmp_path))

    assert len(hourly) == len(HOURS)
    assert hourly["valid_at"].is_unique and hourly["valid_at"].is_monotonic_increasing
    assert report["aligned"]["unique_timestamps"] is True
    assert report["aligned"]["hourly_interval"] is True
    # The two sources answer from different cells; merging them must not invent one coordinate.
    assert hourly["weather_grid_lat"].iloc[0] == pytest.approx(-0.10544816)
    assert hourly["cams_grid_lat"].iloc[0] == pytest.approx(-0.099998474)
    assert report["grid_cells"]["weather"] != report["grid_cells"]["cams"]
    assert len(hotspots) == 3


