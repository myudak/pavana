HOURS = pd.date_range("2024-01-01", periods=48, freq="h", tz="UTC")


def weather_frame(hours: pd.DatetimeIndex = HOURS, lat: float = -0.10544816) -> pd.DataFrame:
    size = len(hours)
    return pd.DataFrame(
        {
            "valid_at": hours,
            "temperature_c": np.linspace(24.0, 30.0, size),
            "rh_pct": np.linspace(70.0, 95.0, size),
            "precip_mm": np.zeros(size),
            "wind_speed_ms": np.linspace(0.5, 3.0, size),
            "wind_dir_from_deg": np.linspace(10.0, 350.0, size),
            "wind_gusts_ms": np.linspace(1.0, 6.0, size),
            "surface_pressure_hpa": np.linspace(1005.0, 1012.0, size),
            "boundary_layer_height_m": np.full(size, np.nan),
            "shortwave_radiation_wm2": np.linspace(0.0, 900.0, size),
            "lat": lat,
            "lon": 109.36087,
        }
    )


def cams_frame(hours: pd.DatetimeIndex = HOURS, lat: float = -0.099998474) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "valid_at": hours,
            "pm25_ug_m3": np.linspace(5.0, 40.0, len(hours)),
            "pm10_ug_m3": np.linspace(6.0, 45.0, len(hours)),
            "lat": lat,
            "lon": 109.399994,
        }
    )


def hotspot_frame() -> pd.DataFrame:
    stamps = pd.to_datetime(["2024-01-01 03:20", "2024-01-01 20:05", "2024-01-02 07:40"], utc=True)
    return pd.DataFrame(
        {
            "lat": [-0.5, 1.0, -2.0],
            "lon": [109.5, 110.5, 111.5],
            "acquired_at": stamps,
            "frp_mw": [np.nan, 4.5, 7.0],
            "satellite": ["N20", "N20", "Terra"],
            "instrument": ["VIIRS", "VIIRS", "MODIS"],
            "source_sensor": ["VIIRS_NOAA20_SP", "VIIRS_NOAA20_SP", "MODIS_SP"],
            "processing": ["SP", "SP", "SP"],
            "brightness": [np.nan, np.nan, 305.0],
            "bright_t31_k": [np.nan, np.nan, 290.0],
            "confidence_pct": [np.nan, np.nan, 61.0],
        }
    )


def write_cache(
    tmp_path,
    *,
    weather: pd.DataFrame | None = None,
    cams: pd.DataFrame | None = None,
    hotspots: pd.DataFrame | None = None,
    weather_kind: str = "reanalysis",
    cams_kind: str = "model",
    manifest: dict | None = None,
):
    folder = tmp_path / "raw" / "open_meteo"
    folder.mkdir(parents=True, exist_ok=True)
    (weather if weather is not None else weather_frame()).to_parquet(
        folder / "weather_test_2024.parquet", index=False
    )
    (cams if cams is not None else cams_frame()).to_parquet(
        folder / "cams_test_2024.parquet", index=False
    )
    for name, kind in (("weather", weather_kind), ("cams", cams_kind)):
        (folder / f"{name}_test_2024.provenance.json").write_text(
            json.dumps({"provider": "Open-Meteo", "dataset": f"{name}-test", "kind": kind})
        )
    processed = tmp_path / "processed"
    processed.mkdir(parents=True, exist_ok=True)
    (hotspots if hotspots is not None else hotspot_frame()).to_parquet(
        processed / "hotspot_kalimantan.parquet", index=False
    )
    if manifest is not None:
        (tmp_path / "manifest.json").write_text(json.dumps(manifest))
    return tmp_path


